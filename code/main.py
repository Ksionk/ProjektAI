import pandas as pd
import torch
from sklearn.model_selection import train_test_split
from sklearn.metrics import accuracy_score, f1_score
from transformers import DistilBertTokenizerFast, DistilBertForSequenceClassification
from transformers import Trainer, TrainingArguments

# 1. Wczytanie i przygotowanie danych
df = pd.read_csv('tmdb_5000_movies.csv')
df = df.dropna(subset=['overview', 'revenue', 'budget'])

# Tworzymy etykiety: 1 (sukces) jeśli przychód > 2x budżet, 0 w przeciwnym razie
df['success'] = (df['revenue'] > (2 * df['budget'])).astype(int)

# Ograniczamy próbkę do 200 filmów dla szybkiego wykonania kodu
df_sample = df.sample(200, random_state=42)
texts = df_sample['overview'].tolist()
labels = df_sample['success'].tolist()

# 2. Podział na zbiór treningowy i testowy
train_texts, test_texts, train_labels, test_labels = train_test_split(texts, labels, test_size=0.2, random_state=42)

# 3. Tokenizacja
tokenizer = DistilBertTokenizerFast.from_pretrained('distilbert-base-uncased')
train_encodings = tokenizer(train_texts, truncation=True, padding=True, max_length=128)
test_encodings = tokenizer(test_texts, truncation=True, padding=True, max_length=128)

class MovieDataset(torch.utils.data.Dataset):
    def __init__(self, encodings, labels):
        self.encodings = encodings
        self.labels = labels

    def __getitem__(self, idx):
        item = {key: torch.tensor(val[idx]) for key, val in self.encodings.items()}
        item['labels'] = torch.tensor(self.labels[idx])
        return item

    def __len__(self):
        return len(self.labels)

train_dataset = MovieDataset(train_encodings, train_labels)
test_dataset = MovieDataset(test_encodings, test_labels)

# 4. Inicjalizacja modelu
model = DistilBertForSequenceClassification.from_pretrained('distilbert-base-uncased', num_labels=2)

# 5. Konfiguracja Fine-tuningu
training_args = TrainingArguments(
    output_dir='./results',
    num_train_epochs=2,
    per_device_train_batch_size=8,
    per_device_eval_batch_size=8,
    weight_decay=0.01,
    logging_steps=10,
    eval_strategy="epoch"
)

def compute_metrics(pred):
    labels = pred.label_ids
    preds = pred.predictions.argmax(-1)
    acc = accuracy_score(labels, preds)
    f1 = f1_score(labels, preds, average='binary')
    return {'accuracy': acc, 'f1': f1}

trainer = Trainer(
    model=model,
    args=training_args,
    train_dataset=train_dataset,
    eval_dataset=test_dataset,
    compute_metrics=compute_metrics
)

# 6. Uruchomienie Treningu i Ewaluacji
print("Rozpoczynanie procesu Fine-tuningu...")
trainer.train()
eval_results = trainer.evaluate()
print(f"\nWyniki: Dokładność (Accuracy): {eval_results['eval_accuracy']:.2f}, F1-Score: {eval_results['eval_f1']:.2f}")

# 7. Test - Przewidywanie dla nowego opisu
test_desc = "A lonely astronaut discovers an ancient alien artifact on Mars that changes human history."
inputs = tokenizer(test_desc, return_tensors="pt", truncation=True, padding=True, max_length=128)

# Przeniesienie wejść na urządzenie, na którym znajduje się model
inputs = {k: v.to(model.device) for k, v in inputs.items()}
outputs = model(**inputs)
prediction = torch.argmax(outputs.logits, dim=1).item()

print(f"\nFilm testowy: '{test_desc}'")
print(f"Wynik predykcji: {'SUKCES FINANSOWY' if prediction == 1 else 'BRAK SUKCESU'}")